// The app icon (design/README.md, "App icon"; ui.md §7): design/icons/mark.svg on a plate, in
// each platform's container, as design/tokens.json appIcon describes. Written as SVG to
// design/app-icon (and the PWA's favicon), and drawn by lib/raster.mjs into every raster a
// client ships: the Windows app's .ico and toast logo, and the PWA's manifest and touch icons.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { loadTokens } from './tokens.mjs';
import { readDesignSvg, parts, fmt } from './svg.mjs';
import { parseColor, contrast, toCssColor } from './color.mjs';
import { render, encodePng, decodePng, encodeIco, decodeIco, samePixels } from './raster.mjs';

export const CONTAINERS = ['windows', 'windowsSmall', 'windows20', 'windows24', 'macos', 'ios', 'android', 'maskable', 'glyph16', 'glyph24'];

// The Windows tiles drawn pixel for pixel from a native cut of the mark (design/icons/mark-<n>.svg),
// smallest first: each is used up to its upTo size, and the full tile above the last.
export const WINDOWS_SMALL = ['windowsSmall', 'windows20', 'windows24'];

// The sizes Windows asks an app icon for: every shell size at 100-200% scale, and 256 for
// the largest views (learn.microsoft.com, "Construct your Windows app's icon").
export const ICO_SIZES = [16, 20, 24, 30, 32, 36, 40, 48, 60, 64, 72, 80, 96, 256];

const HEADER = 'Generated by tools/design-gen from design/tokens.json (appIcon) and design/icons/mark*.svg. Do not edit: change design/ and run node tools/design-gen/generate.mjs';

// tokens.json appIcon, checked, with each mark's shapes: the rasterizer draws circles, rounded
// squares and filled paths of lines and cubics only, so a mark drawn otherwise is refused rather
// than drawn wrong.
export function appIconSpec(designDir) {
  const tokens = loadTokens(designDir);
  const icon = tokens.appIcon;
  if (!icon) { throw new Error('design/tokens.json has no appIcon'); }
  // The mark is a colour (#RRGGBB) or names a colour role, whose dark value it takes.
  const role = /^#/.test(icon.mark ?? '') ? null : tokens.color.role[icon.mark];
  if (!role && !/^#[0-9A-Fa-f]{6}$/.test(icon.mark ?? '')) { throw new Error(`appIcon.mark is "${icon.mark}", neither a #RRGGBB colour nor a colour role`); }
  const colours = { plate: icon.plate, edge: icon.edge, mark: role ? role.dark : icon.mark, monochrome: icon.monochrome };
  for (const [k, v] of Object.entries(colours)) {
    if (parseColor(v).a !== 1) { throw new Error(`appIcon ${k} must be opaque, not ${v}`); }
  }
  // A glyph's rule (ui.md §3): the mark reaches 3:1 against what it sits on.
  const ratio = contrast(colours.mark, colours.plate);
  if (ratio < 3) { throw new Error(`appIcon: the mark is ${ratio.toFixed(2)}:1 on the plate, under 3:1`); }
  const containers = {};
  for (const name of CONTAINERS) {
    const c = icon.container?.[name];
    if (!c) { throw new Error(`appIcon.container.${name} is missing`); }
    for (const k of ['grid', 'plate', 'radius', 'edge', 'mark']) {
      if (!(typeof c[k] === 'number' && Number.isFinite(c[k]) && c[k] >= 0)) { throw new Error(`appIcon.container.${name}.${k} must be a number, 0 or more`); }
    }
    if (!(c.grid > 0 && c.plate > 0 && c.plate <= c.grid && c.mark > 0 && c.mark <= c.plate)) { throw new Error(`appIcon.container.${name}: needs 0 < mark <= plate <= grid`); }
    if (c.radius > c.plate / 2 || c.edge >= c.plate / 2) { throw new Error(`appIcon.container.${name}: radius or edge too large for the plate`); }
    containers[name] = c;
  }
  let below = 0;
  for (const name of WINDOWS_SMALL) {
    const c = containers[name];
    if (!(c.upTo > below)) { throw new Error(`appIcon.container.${name}.upTo must be a size in px, above the smaller tile's`); }
    below = c.upTo;
  }

  const marks = {};
  for (const name of CONTAINERS) {
    const file = containers[name].markFile ?? 'mark';
    if (!/^mark(-\d+)?$/.test(file)) { throw new Error(`appIcon.container.${name}.markFile must name design/icons/mark.svg or mark-<n>.svg`); }
    marks[file] ??= readMark(path.join(designDir, 'icons', `${file}.svg`));
  }
  return { colours, containers, marks, mark: marks.mark };
}

function readMark(markFile) {
  const mark = readDesignSvg(markFile, 'icon');
  const shapes = parts(mark).map((p) => {
    if (p.tag === 'path') { return markPath(markFile, p); }
    if (p.tag !== 'circle') { throw new Error(`${markFile}: the app icon draws circles and paths only, not <${p.tag}>`); }
    const [cx, cy, r] = ['cx', 'cy', 'r'].map((k) => Number(p.attrs[k] ?? 0));
    // The circle as the sprite and the XAML draw it: from 3 o'clock to 9 o'clock and back.
    // Both ends must be where the attributes put them, or a transform has moved the circle
    // (a half turn about another point keeps neither; about its own centre, it swaps them).
    const [start, half] = [p.commands[0].p, p.commands[1].p.slice(5)];
    const near = ([x, y], [ex, ey]) => Math.abs(x - ex) < 1e-9 && Math.abs(y - ey) < 1e-9;
    if (!near(start, [cx + r, cy]) || !near(half, [cx - r, cy])) { throw new Error(`${markFile}: the app icon draws circles without a transform`); }
    if (p.opacity !== 1) { throw new Error(`${markFile}: the app icon draws the mark opaque`); }
    for (const paint of ['fill', 'stroke']) {
      if (![undefined, 'none', 'currentColor'].includes(p.style[paint])) { throw new Error(`${markFile}: the mark draws in currentColor`); }
    }
    const dashes = p.style['stroke-dasharray'];
    if (p.style.stroke === 'currentColor' && dashes !== undefined && dashes !== 'none') { throw new Error(`${markFile}: the app icon draws solid strokes only, not stroke-dasharray="${dashes}"`); }
    return { kind: 'circle', cx, cy, r, fill: p.style.fill === 'currentColor', stroke: p.style.stroke === 'currentColor' ? Number(p.style['stroke-width'] ?? 1) : 0 };
  });
  return { size: mark.size, shapes };
}

// A path is drawn filled, by the nonzero rule, with lines and cubics only: an arc would need
// trigonometry, which isn't rounded the same on every machine.
function markPath(markFile, p) {
  if (p.opacity !== 1) { throw new Error(`${markFile}: the app icon draws the mark opaque`); }
  if (p.style.fill !== 'currentColor' || ![undefined, 'none'].includes(p.style.stroke)) { throw new Error(`${markFile}: the app icon fills a path in currentColor, without a stroke`); }
  const bad = p.commands.find((c) => !'MLCZ'.includes(c.c));
  if (bad) { throw new Error(`${markFile}: the app icon draws paths of M, L, C and Z only, not ${bad.c}`); }
  return { kind: 'path', commands: p.commands };
}

const rgb = (hex) => { const c = parseColor(hex); return { r: c.r, g: c.g, b: c.b }; };

// A container's shapes, in its grid's units: the plate and its edge, then the mark.
export function scene(spec, name, { plate = true, mark = true, markColour = spec.colours.mark } = {}) {
  const c = spec.containers[name];
  const shapes = [];
  if (plate) {
    const at = (c.grid - c.plate) / 2;
    shapes.push({ kind: 'rect', x: at, y: at, width: c.plate, height: c.plate, rx: c.radius, fill: spec.colours.plate });
    // A stroke centred half its width inside the plate's outline, so it ends where the plate does.
    if (c.edge > 0) {
      const e = c.edge / 2;
      shapes.push({ kind: 'rect', x: at + e, y: at + e, width: c.plate - c.edge, height: c.plate - c.edge, rx: Math.max(0, c.radius - e), stroke: spec.colours.edge, strokeWidth: c.edge });
    }
  }
  if (mark) {
    const source = spec.marks[c.markFile ?? 'mark'];
    const k = c.mark / source.size;
    const at = (c.grid - c.mark) / 2;
    for (const m of source.shapes) {
      if (m.kind === 'path') {
        shapes.push({ kind: 'path', commands: m.commands.map(({ c: op, p }) => ({ c: op, p: p.map((v) => at + v * k) })), fill: markColour });
        continue;
      }
      const circle = { kind: 'circle', cx: at + m.cx * k, cy: at + m.cy * k, r: m.r * k };
      if (m.fill) { shapes.push({ ...circle, fill: markColour }); }
      if (m.stroke) { shapes.push({ ...circle, stroke: markColour, strokeWidth: m.stroke * k }); }
    }
  }
  return { grid: c.grid, shapes };
}

export function sceneSvg({ grid, shapes }) {
  const paint = (s) => (s.stroke ? `fill="none" stroke="${toCssColor(s.stroke)}" stroke-width="${fmt(s.strokeWidth)}"` : `fill="${toCssColor(s.fill)}"`);
  const body = shapes.map((s) => (s.kind === 'rect'
    ? `<rect x="${fmt(s.x)}" y="${fmt(s.y)}" width="${fmt(s.width)}" height="${fmt(s.height)}"${s.rx ? ` rx="${fmt(s.rx)}"` : ''} ${paint(s)}/>`
    : s.kind === 'path'
      ? `<path d="${s.commands.map(({ c, p }) => c + p.map(fmt).join(' ')).join('')}" ${paint(s)}/>`
      : `<circle cx="${fmt(s.cx)}" cy="${fmt(s.cy)}" r="${fmt(s.r)}" ${paint(s)}/>`));
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${fmt(grid)}" height="${fmt(grid)}" viewBox="0 0 ${fmt(grid)} ${fmt(grid)}">\n<!-- ${HEADER} -->\n${body.join('\n')}\n</svg>\n`;
}

// Colours an option may name rather than spell: the template black is Apple's convention.
const NAMED = { monochrome: (spec) => spec.colours.monochrome, template: () => '#000000' };

export function rasterize(spec, name, size, options = {}) {
  const markColour = NAMED[options.markColour]?.(spec) ?? options.markColour;
  const s = scene(spec, name, { ...options, ...(markColour ? { markColour } : {}) });
  return render({ grid: s.grid, shapes: s.shapes.map((x) => ({ ...x, fill: x.fill && rgb(x.fill), stroke: x.stroke && rgb(x.stroke) })) }, size);
}

// The Windows tile at a size: a native cut drawn pixel for pixel at 24 px and under, where the
// full mark's strokes would fall between pixels.
export const windowsContainer = (spec, size) => WINDOWS_SMALL.find((n) => size <= spec.containers[n].upTo) ?? 'windows';

// The macOS icon's sizes in points, each at 1x and 2x (Apple's asset catalog), as files by pixel size.
const MAC_POINTS = [16, 32, 128, 256, 512];
const MAC_PIXELS = [...new Set(MAC_POINTS.flatMap((p) => [p, p * 2]))].sort((a, b) => a - b);

const json = (v) => `${JSON.stringify(v, null, 2)}\n`;
const XCODE = { author: 'xcode', version: 1 };

// An Xcode asset catalog for the Apple clients (#260) to take whole: the app icon for macOS and
// for iOS and iPadOS in its three appearances, and the menu bar's template image.
function appleTargets() {
  const cat = 'design/apple/Assets.xcassets';
  const icon = `${cat}/AppIcon.appiconset`;
  const bar = `${cat}/MenuBarIcon.imageset`;
  const images = [
    { filename: 'ios-1024.png', idiom: 'universal', platform: 'ios', size: '1024x1024' },
    { appearances: [{ appearance: 'luminosity', value: 'dark' }], filename: 'ios-1024-dark.png', idiom: 'universal', platform: 'ios', size: '1024x1024' },
    { appearances: [{ appearance: 'luminosity', value: 'tinted' }], filename: 'ios-1024-tinted.png', idiom: 'universal', platform: 'ios', size: '1024x1024' },
    ...MAC_POINTS.flatMap((p) => [1, 2].map((k) => ({ filename: `mac-${p * k}.png`, idiom: 'mac', scale: `${k}x`, size: `${p}x${p}` }))),
  ];
  return {
    [`${cat}/Contents.json`]: { text: json({ info: XCODE }) },
    [`${icon}/Contents.json`]: { text: json({ images, info: XCODE }) },
    // The default icon is opaque, and App Store validation refuses one with an alpha channel.
    [`${icon}/ios-1024.png`]: { png: ['ios', 1024], opaque: true },
    // Dark and tinted: the mark alone on transparency; the system draws the dark ground, or
    // tints the white mark by its luminance.
    [`${icon}/ios-1024-dark.png`]: { png: ['ios', 1024, { plate: false }] },
    [`${icon}/ios-1024-tinted.png`]: { png: ['ios', 1024, { plate: false, markColour: 'monochrome' }] },
    ...Object.fromEntries(MAC_PIXELS.map((px) => [`${icon}/mac-${px}.png`, { png: ['macos', px] }])),
    // A template image is drawn by its alpha alone, so black on transparency; the native 16 px
    // cut, at 1x and doubled at 2x so both scales keep its pixel-aligned strokes.
    [`${bar}/Contents.json`]: { text: json({ images: [{ filename: 'menubar.png', idiom: 'universal', scale: '1x' }, { filename: 'menubar@2x.png', idiom: 'universal', scale: '2x' }], info: XCODE, properties: { 'template-rendering-intent': 'template' } }) },
    [`${bar}/menubar.png`]: { png: ['glyph16', 16, { plate: false, markColour: 'template' }] },
    [`${bar}/menubar@2x.png`]: { png: ['glyph16', 32, { plate: false, markColour: 'template' }] },
  };
}

// Android: the adaptive icon's layers and the status-bar notification icon as VectorDrawables,
// which take SVG path data as it is. The notification icon is white on transparency, as Android
// requires, on the 24 dp grid from the native 24 px cut.
function androidTargets(spec) {
  const vector = (name, colour, { size, grid, plate = false } = {}) => {
    const sc = scene(spec, name, { plate, markColour: colour });
    const paths = sc.shapes.map((x) => {
      if (x.kind !== 'path') { throw new Error('the Android vectors draw the mark as paths only'); }
      return `    <path android:fillColor="${toCssColor(colour)}" android:pathData="${x.commands.map(({ c, p }) => c + p.map(fmt).join(' ')).join('')}"/>`;
    });
    return { text: `<?xml version="1.0" encoding="utf-8"?>\n<!-- ${HEADER} -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="${size}dp" android:height="${size}dp" android:viewportWidth="${grid}" android:viewportHeight="${grid}">\n${paths.join('\n')}\n</vector>\n` };
  };
  const a = spec.containers.android.grid;
  return {
    'design/android/drawable/ic_launcher_foreground.xml': vector('android', spec.colours.mark, { size: a, grid: a }),
    'design/android/drawable/ic_launcher_monochrome.xml': vector('android', spec.colours.monochrome, { size: a, grid: a }),
    'design/android/drawable/ic_stat_slipgates.xml': vector('glyph24', '#FFFFFF', { size: 24, grid: 24 }),
    // The adaptive icon (API 26+), with the monochrome layer Android 13+ tints for themed icons.
    'design/android/mipmap-anydpi-v26/ic_launcher.xml': { text: `<?xml version="1.0" encoding="utf-8"?>\n<!-- ${HEADER} -->\n<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n    <background android:drawable="@color/ic_launcher_background"/>\n    <foreground android:drawable="@drawable/ic_launcher_foreground"/>\n    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>\n</adaptive-icon>\n` },
    'design/android/values/ic_launcher_background.xml': { text: `<?xml version="1.0" encoding="utf-8"?>\n<!-- ${HEADER} -->\n<resources>\n    <color name="ic_launcher_background">${spec.colours.plate}</color>\n</resources>\n` },
  };
}

// Every file the app icon is generated into: { rel: { svg } | { text } | { png: [container,
// size, options] } | { ico: [sizes] } }. Rasters are described, not drawn, so listing them
// costs nothing.
export function appIconTargets(spec) {
  const svg = (name, options) => ({ svg: sceneSvg(scene(spec, name, options)) });
  const windows = svg('windows');
  return {
    'design/app-icon/windows.svg': windows,
    'design/app-icon/windows-small.svg': svg('windowsSmall'),
    'design/app-icon/windows-20.svg': svg('windows20'),
    'design/app-icon/windows-24.svg': svg('windows24'),
    'design/app-icon/macos.svg': svg('macos'),
    'design/app-icon/ios.svg': svg('ios'),
    'design/app-icon/android-background.svg': svg('android', { mark: false }),
    'design/app-icon/android-foreground.svg': svg('android', { plate: false }),
    'design/app-icon/android-monochrome.svg': svg('android', { plate: false, markColour: spec.colours.monochrome }),
    'design/app-icon/maskable.svg': svg('maskable'),
    'pwa/icon.svg': windows,
    'pwa/icons/icon-192.png': { png: ['windows', 192] },
    'pwa/icons/icon-512.png': { png: ['windows', 512] },
    'pwa/icons/maskable-192.png': { png: ['maskable', 192] },
    'pwa/icons/maskable-512.png': { png: ['maskable', 512] },
    'pwa/icons/apple-touch-icon.png': { png: ['ios', 180] },
    'src/AgentBridge.App/Assets/AgentBridge.ico': { ico: ICO_SIZES },
    'src/AgentBridge.App/Assets/AgentBridge.png': { png: ['windows', 256] },
    ...appleTargets(),
    ...androidTargets(spec),
  };
}

const sameText = (a, b) => a.replace(/\r\n/g, '\n') === b.replace(/\r\n/g, '\n');

function upToDate(spec, file, target) {
  if (!existsSync(file)) { return false; }
  if (target.svg ?? target.text) { return sameText(readFileSync(file, 'utf8'), target.svg ?? target.text); }
  if (target.png) {
    const img = decodePng(readFileSync(file));
    return Boolean(img) && img.opaque === Boolean(target.opaque) && samePixels(img, rasterize(spec, ...target.png));
  }
  const images = decodeIco(readFileSync(file));
  return Boolean(images) && images.length === target.ico.length
    && target.ico.every((size, i) => samePixels(images[i], rasterize(spec, windowsContainer(spec, size), size)));
}

function bytes(spec, target) {
  if (target.svg ?? target.text) { return target.svg ?? target.text; }
  if (target.png) { return encodePng(rasterize(spec, ...target.png), { opaque: Boolean(target.opaque) }); }
  return encodeIco(target.ico.map((size) => rasterize(spec, windowsContainer(spec, size), size)));
}

export function staleAppIcons(root) {
  const spec = appIconSpec(path.join(root, 'design'));
  return Object.entries(appIconTargets(spec)).filter(([rel, t]) => !upToDate(spec, path.join(root, rel), t)).map(([rel]) => rel);
}

export function writeAppIcons(root) {
  const spec = appIconSpec(path.join(root, 'design'));
  const written = [];
  for (const [rel, t] of Object.entries(appIconTargets(spec))) {
    const f = path.join(root, rel);
    if (upToDate(spec, f, t)) { continue; }
    mkdirSync(path.dirname(f), { recursive: true });
    writeFileSync(f, bytes(spec, t));
    written.push(rel);
  }
  return written;
}
