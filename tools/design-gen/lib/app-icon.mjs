// The app icon (design/README.md, "App icon"; ui.md §7): design/icons/mark.svg on a plate, in
// each platform's container, as design/tokens.json appIcon describes. Written as SVG to
// design/app-icon (and the PWA's favicon), and drawn by lib/raster.mjs into every raster a
// client ships: the Windows app's .ico and toast logo, and the PWA's manifest and touch icons.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { loadTokens } from './tokens.mjs';
import { readDesignSvg, parts, fmt } from './svg.mjs';
import { parseColor, contrast, toCssColor } from './color.mjs';
import { render, encodePng, decodePng, encodeIco, decodeIco, samePixels } from './raster.mjs';

export const CONTAINERS = ['windows', 'windowsSmall', 'macos', 'ios', 'android', 'maskable'];

// The sizes Windows asks an app icon for: every shell size at 100-200% scale, and 256 for
// the largest views (learn.microsoft.com, "Construct your Windows app's icon").
export const ICO_SIZES = [16, 20, 24, 30, 32, 36, 40, 48, 60, 64, 72, 80, 96, 256];

const HEADER = 'Generated by tools/design-gen from design/tokens.json (appIcon) and design/icons/mark.svg. Do not edit: change design/ and run node tools/design-gen/generate.mjs';

// tokens.json appIcon, checked, with the mark's circles: the rasterizer draws circles and
// rounded squares only, so a mark drawn otherwise is refused rather than drawn wrong.
export function appIconSpec(designDir) {
  const tokens = loadTokens(designDir);
  const icon = tokens.appIcon;
  if (!icon) { throw new Error('design/tokens.json has no appIcon'); }
  const role = tokens.color.role[icon.mark];
  if (!role) { throw new Error(`appIcon.mark names "${icon.mark}", which is not a colour role`); }
  const colours = { plate: icon.plate, edge: icon.edge, mark: role.dark, monochrome: icon.monochrome };
  for (const [k, v] of Object.entries(colours)) {
    if (parseColor(v).a !== 1) { throw new Error(`appIcon ${k} must be opaque, not ${v}`); }
  }
  // A glyph's rule (ui.md §3): the mark reaches 3:1 against what it sits on.
  const ratio = contrast(colours.mark, colours.plate);
  if (ratio < 3) { throw new Error(`appIcon: the mark is ${ratio.toFixed(2)}:1 on the plate, under 3:1`); }
  const containers = {};
  for (const name of CONTAINERS) {
    const c = icon.container?.[name];
    if (!c) { throw new Error(`appIcon.container.${name} is missing`); }
    for (const k of ['grid', 'plate', 'radius', 'edge', 'mark']) {
      if (!(typeof c[k] === 'number' && Number.isFinite(c[k]) && c[k] >= 0)) { throw new Error(`appIcon.container.${name}.${k} must be a number, 0 or more`); }
    }
    if (!(c.grid > 0 && c.plate > 0 && c.plate <= c.grid && c.mark > 0 && c.mark <= c.plate)) { throw new Error(`appIcon.container.${name}: needs 0 < mark <= plate <= grid`); }
    if (c.radius > c.plate / 2 || c.edge >= c.plate / 2) { throw new Error(`appIcon.container.${name}: radius or edge too large for the plate`); }
    containers[name] = c;
  }
  if (!(containers.windowsSmall.upTo > 0)) { throw new Error('appIcon.container.windowsSmall.upTo must be a size in px'); }

  const markFile = path.join(designDir, 'icons', 'mark.svg');
  const mark = readDesignSvg(markFile, 'icon');
  const circles = parts(mark).map((p) => {
    if (p.tag !== 'circle') { throw new Error(`${markFile}: the app icon draws circles only, not <${p.tag}>`); }
    const [cx, cy, r] = ['cx', 'cy', 'r'].map((k) => Number(p.attrs[k] ?? 0));
    // The circle as the sprite and the XAML draw it: from 3 o'clock to 9 o'clock and back.
    // Both ends must be where the attributes put them, or a transform has moved the circle
    // (a half turn about another point keeps neither; about its own centre, it swaps them).
    const [start, half] = [p.commands[0].p, p.commands[1].p.slice(5)];
    const near = ([x, y], [ex, ey]) => Math.abs(x - ex) < 1e-9 && Math.abs(y - ey) < 1e-9;
    if (!near(start, [cx + r, cy]) || !near(half, [cx - r, cy])) { throw new Error(`${markFile}: the app icon draws circles without a transform`); }
    if (p.opacity !== 1) { throw new Error(`${markFile}: the app icon draws the mark opaque`); }
    for (const paint of ['fill', 'stroke']) {
      if (![undefined, 'none', 'currentColor'].includes(p.style[paint])) { throw new Error(`${markFile}: the mark draws in currentColor`); }
    }
    const dashes = p.style['stroke-dasharray'];
    if (p.style.stroke === 'currentColor' && dashes !== undefined && dashes !== 'none') { throw new Error(`${markFile}: the app icon draws solid strokes only, not stroke-dasharray="${dashes}"`); }
    return { cx, cy, r, fill: p.style.fill === 'currentColor', stroke: p.style.stroke === 'currentColor' ? Number(p.style['stroke-width'] ?? 1) : 0 };
  });
  return { colours, containers, mark: { size: mark.size, circles } };
}

const rgb = (hex) => { const c = parseColor(hex); return { r: c.r, g: c.g, b: c.b }; };

// A container's shapes, in its grid's units: the plate and its edge, then the mark.
export function scene(spec, name, { plate = true, mark = true, markColour = spec.colours.mark } = {}) {
  const c = spec.containers[name];
  const shapes = [];
  if (plate) {
    const at = (c.grid - c.plate) / 2;
    shapes.push({ kind: 'rect', x: at, y: at, width: c.plate, height: c.plate, rx: c.radius, fill: spec.colours.plate });
    // A stroke centred half its width inside the plate's outline, so it ends where the plate does.
    if (c.edge > 0) {
      const e = c.edge / 2;
      shapes.push({ kind: 'rect', x: at + e, y: at + e, width: c.plate - c.edge, height: c.plate - c.edge, rx: Math.max(0, c.radius - e), stroke: spec.colours.edge, strokeWidth: c.edge });
    }
  }
  if (mark) {
    const k = c.mark / spec.mark.size;
    const at = (c.grid - c.mark) / 2;
    for (const m of spec.mark.circles) {
      const circle = { kind: 'circle', cx: at + m.cx * k, cy: at + m.cy * k, r: m.r * k };
      if (m.fill) { shapes.push({ ...circle, fill: markColour }); }
      if (m.stroke) { shapes.push({ ...circle, stroke: markColour, strokeWidth: m.stroke * k }); }
    }
  }
  return { grid: c.grid, shapes };
}

export function sceneSvg({ grid, shapes }) {
  const paint = (s) => (s.stroke ? `fill="none" stroke="${toCssColor(s.stroke)}" stroke-width="${fmt(s.strokeWidth)}"` : `fill="${toCssColor(s.fill)}"`);
  const body = shapes.map((s) => (s.kind === 'rect'
    ? `<rect x="${fmt(s.x)}" y="${fmt(s.y)}" width="${fmt(s.width)}" height="${fmt(s.height)}"${s.rx ? ` rx="${fmt(s.rx)}"` : ''} ${paint(s)}/>`
    : `<circle cx="${fmt(s.cx)}" cy="${fmt(s.cy)}" r="${fmt(s.r)}" ${paint(s)}/>`));
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${fmt(grid)}" height="${fmt(grid)}" viewBox="0 0 ${fmt(grid)} ${fmt(grid)}">\n<!-- ${HEADER} -->\n${body.join('\n')}\n</svg>\n`;
}

export function rasterize(spec, name, size, options) {
  const s = scene(spec, name, options);
  return render({ grid: s.grid, shapes: s.shapes.map((x) => ({ ...x, fill: x.fill && rgb(x.fill), stroke: x.stroke && rgb(x.stroke) })) }, size);
}

// The Windows tile at a size: the small one where the full one's ring would be a hairline.
export const windowsContainer = (spec, size) => (size <= spec.containers.windowsSmall.upTo ? 'windowsSmall' : 'windows');

// Every file the app icon is generated into: { rel: { svg } | { png: [container, size] } |
// { ico: [sizes] } }. Rasters are described, not drawn, so listing them costs nothing.
export function appIconTargets(spec) {
  const svg = (name, options) => ({ svg: sceneSvg(scene(spec, name, options)) });
  const windows = svg('windows');
  return {
    'design/app-icon/windows.svg': windows,
    'design/app-icon/windows-small.svg': svg('windowsSmall'),
    'design/app-icon/macos.svg': svg('macos'),
    'design/app-icon/ios.svg': svg('ios'),
    'design/app-icon/android-background.svg': svg('android', { mark: false }),
    'design/app-icon/android-foreground.svg': svg('android', { plate: false }),
    'design/app-icon/android-monochrome.svg': svg('android', { plate: false, markColour: spec.colours.monochrome }),
    'design/app-icon/maskable.svg': svg('maskable'),
    'pwa/icon.svg': windows,
    'pwa/icons/icon-192.png': { png: ['windows', 192] },
    'pwa/icons/icon-512.png': { png: ['windows', 512] },
    'pwa/icons/maskable-192.png': { png: ['maskable', 192] },
    'pwa/icons/maskable-512.png': { png: ['maskable', 512] },
    'pwa/icons/apple-touch-icon.png': { png: ['ios', 180] },
    'src/AgentBridge.App/Assets/AgentBridge.ico': { ico: ICO_SIZES },
    'src/AgentBridge.App/Assets/AgentBridge.png': { png: ['windows', 256] },
  };
}

const sameText = (a, b) => a.replace(/\r\n/g, '\n') === b.replace(/\r\n/g, '\n');

function upToDate(spec, file, target) {
  if (!existsSync(file)) { return false; }
  if (target.svg) { return sameText(readFileSync(file, 'utf8'), target.svg); }
  if (target.png) { return samePixels(decodePng(readFileSync(file)), rasterize(spec, ...target.png)); }
  const images = decodeIco(readFileSync(file));
  return Boolean(images) && images.length === target.ico.length
    && target.ico.every((size, i) => samePixels(images[i], rasterize(spec, windowsContainer(spec, size), size)));
}

function bytes(spec, target) {
  if (target.svg) { return target.svg; }
  if (target.png) { return encodePng(rasterize(spec, ...target.png)); }
  return encodeIco(target.ico.map((size) => rasterize(spec, windowsContainer(spec, size), size)));
}

export function staleAppIcons(root) {
  const spec = appIconSpec(path.join(root, 'design'));
  return Object.entries(appIconTargets(spec)).filter(([rel, t]) => !upToDate(spec, path.join(root, rel), t)).map(([rel]) => rel);
}

export function writeAppIcons(root) {
  const spec = appIconSpec(path.join(root, 'design'));
  const written = [];
  for (const [rel, t] of Object.entries(appIconTargets(spec))) {
    const f = path.join(root, rel);
    if (upToDate(spec, f, t)) { continue; }
    mkdirSync(path.dirname(f), { recursive: true });
    writeFileSync(f, bytes(spec, t));
    written.push(rel);
  }
  return written;
}
