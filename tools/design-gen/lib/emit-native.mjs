// The Apple and Android apps' copies of the bundled fonts (docs/design/ui.md §4.1, #544):
// for Apple, a Swift file naming every real face by its PostScript name, with Dynamic Type
// scaling, and the Info.plist entries that register the files; for Android, the font files
// under res/font names and a font-family XML per family. Every weight and style the ramps use is
// a real face in each (ui.md §4.2), so neither platform has a reason to synthesize one.

import { readFileSync } from 'node:fs';
import path from 'node:path';
import { bundledFonts, WEIGHT_NAMES } from './tokens.mjs';

const header = (from, open, close) => `${open} Generated by tools/design-gen from ${from}.
   Do not edit: change design/ and run node tools/design-gen/generate.mjs.
   CI fails when this file is stale against design/. ${close}`;

// The files each platform bundles from a family: a variable family's pair, or a static one's TTF
// per face, each with the PostScript name of every face it holds.
function appleFaces(font, manifest) {
  if (font.variable) {
    return font.faces.map((f) => {
      const v = manifest.variable?.find((x) => x.style === f.style);
      const ps = v?.instances?.[String(f.weight)];
      if (!ps) { throw new Error(`${font.dir}/faces.json names no ${f.weight} ${f.style} instance`); }
      return { ...f, ps, file: `${font.variableFiles.find((x) => x.style === f.style).file}.ttf` };
    });
  }
  return font.faces.map((f) => {
    const m = manifest.faces.find((x) => x.weight === f.weight && x.style === f.style);
    if (!m) { throw new Error(`${font.dir}/faces.json has no ${f.weight} ${f.style} face`); }
    return { ...f, ps: m.postscript, file: `${f.file}.ttf` };
  });
}

const swiftCase = (font) => font.kind;
const swiftWeight = (w) => WEIGHT_NAMES[w].toLowerCase();

export function appleFontsSwift(tokens, manifests) {
  const fonts = bundledFonts(tokens);
  const faces = fonts.flatMap((font) => appleFaces(font, manifests[font.kind]).map((f) => ({ font, ...f })));
  const files = [...new Set(faces.map((f) => f.file))];
  const weights = [...new Set(faces.map((f) => f.weight))].sort();
  return `${header('design/tokens.json and each design/fonts family\'s faces.json', '//', '').replace(/\n   /g, '\n// ').trimEnd()}

import SwiftUI
#if canImport(UIKit)
import UIKit
#elseif canImport(AppKit)
import AppKit
#endif

/// The bundled families (docs/design/ui.md §4.1): ${fonts.map((f) => f.family).join(' and ')}.
/// Every weight and style the ramps use is a real face, named here by its PostScript name, so
/// nothing is synthesized (ui.md §4.2). Ask for a weight or an italic through these rather than
/// applying \`.bold()\` or \`.italic()\` to another face. The files are registered by
/// SlipgatesFonts.plist: UIAppFonts on iOS and iPadOS, ATSApplicationFontsPath on macOS.
public enum SlipgatesFont {
    public enum Family: CaseIterable { ${fonts.map((f) => `case ${swiftCase(f)}`).join('; ')} }

    public enum Weight: Int, CaseIterable {
${weights.map((w) => `        case ${swiftWeight(w)} = ${w}`).join('\n')}
    }

    /// The PostScript name of a real face.
    public static func name(_ family: Family, _ weight: Weight = .regular, italic: Bool = false) -> String {
        switch (family, weight, italic) {
${faces.map((f) => `        case (.${swiftCase(f.font)}, .${swiftWeight(f.weight)}, ${f.style === 'italic'}): return "${f.ps}"`).join('\n')}
        }
    }

    /// SwiftUI: the face at a ramp size, scaled with Dynamic Type relative to \`style\`
    /// (UIFontMetrics underneath). macOS has no Dynamic Type, so there it stays at \`size\`.
    public static func font(_ family: Family, size: CGFloat, weight: Weight = .regular, italic: Bool = false, relativeTo style: Font.TextStyle = .body) -> Font {
        .custom(name(family, weight, italic: italic), size: size, relativeTo: style)
    }

#if canImport(UIKit)
    /// UIKit: the face, scaled for Dynamic Type by UIFontMetrics for \`textStyle\`. Set
    /// adjustsFontForContentSizeCategory on the view so it follows a change of setting.
    public static func uiFont(_ family: Family, size: CGFloat, weight: Weight = .regular, italic: Bool = false, textStyle: UIFont.TextStyle = .body) -> UIFont {
        let face = name(family, weight, italic: italic)
        guard let base = UIFont(name: face, size: size) else { preconditionFailure("\\(face) is not registered: check UIAppFonts") }
        return UIFontMetrics(forTextStyle: textStyle).scaledFont(for: base)
    }
#elseif canImport(AppKit)
    /// AppKit: the face at a ramp size; macOS's ramp is fixed (ui.md §4.3).
    public static func nsFont(_ family: Family, size: CGFloat, weight: Weight = .regular, italic: Bool = false) -> NSFont {
        let face = name(family, weight, italic: italic)
        guard let font = NSFont(name: face, size: size) else { preconditionFailure("\\(face) is not registered: check ATSApplicationFontsPath") }
        return font
    }
#endif

    /// Every font file the app bundles, in its Fonts folder, as SlipgatesFonts.plist lists them.
    public static let files: [String] = [
${files.map((f) => `        "${f}",`).join('\n')}
    ]
}
`;
}

export function appleFontsPlist(tokens, manifests) {
  const files = [...new Set(bundledFonts(tokens).flatMap((font) => appleFaces(font, manifests[font.kind]).map((f) => f.file)))];
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
${header('design/tokens.json', '<!--', '-->')}
<!-- Merge into the app's Info.plist, and copy each file below from design/fonts (ttf/) into the
     bundle's Fonts folder. iOS and iPadOS register what UIAppFonts lists; macOS everything in
     ATSApplicationFontsPath, relative to Contents/Resources. Every face is registered, so the
     system has a real face for each weight and style (docs/design/ui.md §4.2). -->
<plist version="1.0">
<dict>
    <key>UIAppFonts</key>
    <array>
${files.map((f) => `        <string>Fonts/${f}</string>`).join('\n')}
    </array>
    <key>ATSApplicationFontsPath</key>
    <string>Fonts</string>
</dict>
</plist>
`;
}

// Android: res/font names are lower case, with underscores, and a family's XML may not share a
// name with a file, so a variable family's files are <family>_upright and <family>_italic.
const resName = (s) => s.replace('SemiBold', 'Semibold').replace(/([a-z])([A-Z])/g, '$1_$2').replace(/-/g, '_').toLowerCase();

function androidFiles(font) {
  const family = resName(font.stem);
  if (font.variable) {
    return font.variableFiles.map((v) => ({ style: v.style, res: `${family}_${v.style === 'italic' ? 'italic' : 'upright'}`, from: `ttf/${v.file}.ttf` }));
  }
  return font.faces.map((f) => ({ weight: f.weight, style: f.style, res: resName(f.file), from: `ttf/${f.file}.ttf` }));
}

// Every generated Android file: the font files, copied byte for byte, and one XML per family.
export function androidFonts(root, tokens) {
  const out = {};
  for (const font of bundledFonts(tokens)) {
    const files = androidFiles(font);
    for (const f of files) { out[`design/android/font/${f.res}.ttf`] = readFileSync(path.join(root, font.dir, f.from)); }
    const entries = font.faces.map((face) => {
      const file = font.variable ? files.find((f) => f.style === face.style) : files.find((f) => f.weight === face.weight && f.style === face.style);
      const variation = font.variable ? ` android:fontVariationSettings="'wght' ${face.weight}"` : '';
      return `    <font android:font="@font/${file.res}" android:fontWeight="${face.weight}" android:fontStyle="${face.style}"${variation} />`;
    });
    out[`design/android/font/${resName(font.stem)}.xml`] = `<?xml version="1.0" encoding="utf-8"?>
${header(`design/tokens.json and ${font.dir}`, '<!--', '-->')}
<!-- ${font.family} (docs/design/ui.md §4.1): a <font> for every weight and style the ramps
     use, each a real face, so Android never fakes one (ui.md §4.2).${font.variable ? `
     The variable files are set to each weight.` : ''} In Compose, the same faces, with
     FontSynthesis.None. -->
<font-family xmlns:android="http://schemas.android.com/apk/res/android">
${entries.join('\n')}
</font-family>
`;
  }
  return out;
}
