// Assembles the PWA for publishing: copies the app, writes config.js with the relay it
// talks to, and puts the Content-Security-Policy in the page (GitHub Pages cannot send
// headers). The tests serve exactly this output, so they run under the same policy.
//
// The app's scripts are bundled and minified (esbuild) into bundle/, under names that carry their
// content's hash, and the page loads that; js/ is copied as it is beside it, the source layout the
// tests import modules from.
//
//   node tools/build-site.mjs --out <dir> [--relay https://relay.example] [--blob-origin https://<account>.blob.core.windows.net]
import { cpSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath, pathToFileURL } from 'node:url';

const appRoot = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
// design/: the generated tokens.css and sprite.svg (tools/design-gen); copyFonts adds the fonts.
// icon.svg and icons/: the app icon, generated by tools/design-gen too.
const FILES = ['index.html', 'app.css', 'text-size-boot.js', 'design', 'sw.js', 'manifest.webmanifest', 'icon.svg', 'icons', 'js', 'fixtures'];

export function relayOrigin(relay) {
  if (!relay) { return ''; }
  const u = new URL(relay);
  if (!['https:', 'http:'].includes(u.protocol) || u.origin !== relay.replace(/\/$/, '')) {
    throw new Error(`--relay must be an origin like https://relay.example, not ${relay}`);
  }
  return u.origin;
}

// The relay's blob store, where large attachments are uploaded straight from the page: an Azure
// Storage account's blob endpoint, and nothing else.
export function blobOrigin(url) {
  let u = null;
  try { u = new URL(url); } catch { /* refused below */ }
  if (!u || u.protocol !== 'https:' || !/^[a-z0-9]{3,24}\.blob\.core\.windows\.net$/.test(u.hostname) || u.origin !== url.replace(/\/$/, '')) {
    throw new Error(`--blob-origin must be an origin like https://account.blob.core.windows.net, not ${url}`);
  }
  return u.origin;
}

function feedbackConfiguration(keyId, publicKey) {
  if (!keyId && !publicKey) { return { keyId: '', publicKey: '' }; }
  if (typeof keyId !== 'string' || !/^[A-Za-z0-9._-]{1,64}$/.test(keyId)) {
    throw new Error('--feedback-key-id must be 1-64 ASCII letters, digits, dot, underscore or hyphen');
  }
  const decoded = typeof publicKey === 'string' ? Buffer.from(publicKey, 'base64url') : null;
  if (typeof publicKey !== 'string' || !/^[A-Za-z0-9_-]{43}$/.test(publicKey) || decoded.length !== 32 || decoded.toString('base64url') !== publicKey) {
    throw new Error('--feedback-public-key must be a base64url-encoded 32-byte X25519 public key');
  }
  return { keyId, publicKey };
}

// The build's time, from the commit's committer date: written to config.js and version.json for
// Settings to show. An ISO time with a zone, or nothing (a local build, shown as dev).
export function builtAt(value) {
  if (!value) { return ''; }
  const when = /^\d{4}-\d\d-\d\dT\d\d:\d\d:\d\d(\.\d+)?(Z|[+-]\d\d:\d\d)$/.test(value) ? new Date(value) : null;
  if (!when || Number.isNaN(when.getTime())) { throw new Error(`--built-at must be an ISO time with a zone like 2026-11-07T12:30:00-08:00, not ${value}`); }
  return when.toISOString();
}

export function contentSecurityPolicy(relay, blobOrigins = []) {
  const origin = relayOrigin(relay);
  // 'self' does not cover WebSockets in every Safari, so the socket origin is named too.
  const connect = (origin ? ` ${origin} ${origin.replace(/^http/, 'ws')}` : '') + blobOrigins.map((b) => ` ${blobOrigin(b)}`).join('');
  // Scripts and styles only from this site, network only to the relay and its blob store: a
  // page that holds the device key must not be able to load or send anything else. blob:
  // images are the thumbnails of files about to be attached, made in the page from their own
  // bytes.
  return `default-src 'self'; script-src 'self'; style-src 'self'; img-src 'self' data: blob:; connect-src 'self'${connect}; object-src 'none'; base-uri 'none'; form-action 'none'`;
}

// The bundled fonts' WOFF2s and their licences, from the repository's design/ (design/tokens.json
// type.sans.files and type.mono.files) into design/fonts/, where design/tokens.css's @font-face
// rules look. Copied at build time rather than kept twice in the repository; each family's OFL
// travels with it, as <Stem>-OFL.txt.
export function copyFonts(out, repo = path.dirname(appRoot)) {
  const type = JSON.parse(readFileSync(path.join(repo, 'design', 'tokens.json'), 'utf8')).type;
  const to = path.join(out, 'design', 'fonts');
  const copied = [];
  for (const font of [type.sans, type.mono].filter((f) => f?.files)) {
    const from = path.join(repo, font.files);
    const stem = font.family[0].replace(/\s+/g, '');
    mkdirSync(to, { recursive: true });
    for (const f of readdirSync(path.join(from, 'woff2')).filter((x) => x.endsWith('.woff2'))) {
      cpSync(path.join(from, 'woff2', f), path.join(to, f));
      copied.push(f);
    }
    cpSync(path.join(from, 'OFL.txt'), path.join(to, `${stem}-OFL.txt`));
    copied.push(`${stem}-OFL.txt`);
  }
  return copied;
}

export function buildSite({ out, relay = '', blobOrigins = [], version = 'dev', builtAt: stamp = '', feedbackKeyId = '', feedbackPublicKey = '', root = appRoot }) {
  const origin = relayOrigin(relay);
  const feedback = feedbackConfiguration(feedbackKeyId, feedbackPublicKey);
  const built = builtAt(stamp);
  if (typeof version !== 'string' || !version || version.length > 128) { throw new Error('--version must be 1-128 characters'); }
  rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });
  for (const f of FILES) { cpSync(path.join(root, f), path.join(out, f), { recursive: true }); }
  copyFonts(out);
  writeFileSync(path.join(out, 'config.js'), [
    `export const RELAY = ${JSON.stringify(origin)};`,
    `export const APP_VERSION = ${JSON.stringify(version)};`,
    `export const BUILT_AT = ${JSON.stringify(built)};`,
    `export const FEEDBACK_KEY_ID = ${JSON.stringify(feedback.keyId)};`,
    `export const FEEDBACK_PUBLIC_KEY = ${JSON.stringify(feedback.publicKey)};`,
    '',
  ].join('\n'));
  // Read by people and tools; sw.js answers it from the network only and never keeps it.
  writeFileSync(path.join(out, 'version.json'), `${JSON.stringify({ version, builtAt: built })}\n`);
  const index = path.join(out, 'index.html');
  const html = readFileSync(index, 'utf8');
  const marker = '<meta charset="utf-8">';
  if (!html.includes(marker)) { throw new Error('index.html has no <meta charset="utf-8"> to put the policy after'); }
  const csp = contentSecurityPolicy(origin, blobOrigins).replace(/"/g, '&quot;');
  writeFileSync(index, html.replace(marker, `${marker}\n  <meta http-equiv="Content-Security-Policy" content="${csp}">`));
  bundle(out);
  checkShell(out);
  stampWorker(out);
  return out;
}

// The worker's shell, the files it keeps for a release, is listed by hand in sw.js (and the
// bundle by bundle() below). A release installs whole or not at all, so one name the site lacks
// would leave every installed app on the release it has, for good (#650): the build refuses it.
export function shellFiles(source) {
  const list = source.match(/const SHELL = \[([\s\S]*?)\];/);
  const bundled = source.match(/const BUNDLE = \[([^\]]*)\];/);
  if (!list || !bundled) { throw new Error('sw.js has no SHELL and BUNDLE lists to check'); }
  return [...`${list[1]}${bundled[1]}`.matchAll(/'\.\/([^']*)'/g)].map((m) => m[1]);
}

const isFile = (p) => { try { return statSync(p).isFile(); } catch { return false; } };

function checkShell(out) {
  const listed = shellFiles(readFileSync(path.join(out, 'sw.js'), 'utf8'));
  // A kept copy would show the release that installed, never the one now published.
  if (listed.includes('version.json')) { throw new Error('sw.js keeps version.json in its shell, so it could never tell a newer release: it must be fetched from the network only'); }
  const missing = listed.filter((f) => !isFile(path.join(out, f || 'index.html')));
  if (missing.length) { throw new Error(`sw.js keeps files the site lacks, so no release could install: ${missing.join(', ')}`); }
}

// 53 modules, each a request, in an import chain 8 deep, took 4.5 s to a first session on a
// throttled phone, and the demo's pretend hosts came along for everyone (#609). So js/main.js is
// bundled into one entry and the chunks it imports: the demo's own chunk only when the demo asks
// for it (main.js imports demo.js dynamically). The page loads the entry and preloads the chunks
// it imports, so nothing waits on a chain; the worker precaches them (sw.js BUNDLE). Names carry
// a hash of their content, so a release's files are never taken for another's. The output is
// deterministic: the same app builds the same bundle, and the same worker.
const BUNDLE_DIR = 'bundle';

function bundle(out) {
  // Loaded here, not at the top: the CSP and relay checks above need no packages.
  const { buildSync } = createRequire(import.meta.url)('esbuild');
  rmSync(path.join(out, BUNDLE_DIR), { recursive: true, force: true });
  const { metafile } = buildSync({
    absWorkingDir: out,
    entryPoints: ['js/main.js'],
    outdir: BUNDLE_DIR,
    bundle: true,
    splitting: true,
    format: 'esm',
    // The app's own syntax, as it is: the browsers it runs on already take it.
    target: 'esnext',
    minify: true,
    // Error messages and anything else that reads a function's or class's name keep it.
    keepNames: true,
    entryNames: '[name]-[hash]',
    chunkNames: '[name]-[hash]',
    metafile: true,
    logLevel: 'error',
  });
  const slash = (f) => f.split(path.sep).join('/');
  const outputs = new Map(Object.entries(metafile.outputs).map(([file, o]) => [slash(file), o]));
  const entry = [...outputs].find(([, o]) => o.entryPoint === 'js/main.js')?.[0];
  if (!entry) { throw new Error('esbuild wrote no bundle for js/main.js'); }
  // The demo's chunk: esbuild makes each module imported dynamically an entry point of its own.
  const demo = [...outputs].filter(([f, o]) => f !== entry && (o.entryPoint === 'js/demo.js' || Object.keys(o.inputs).some((i) => slash(i) === 'js/demo.js'))).map(([f]) => f);
  if (demo.length !== 1) { throw new Error('esbuild wrote no chunk of its own for js/demo.js: main.js must import it only dynamically'); }
  // Everything the entry reaches, by the imports in the kinds asked for, the demo's chunk aside.
  const reach = (kinds) => {
    const seen = new Set([entry]);
    for (const file of seen) {
      for (const i of outputs.get(file).imports) {
        if (!i.external && kinds.includes(i.kind) && !demo.includes(slash(i.path))) { seen.add(slash(i.path)); }
      }
    }
    return [...seen].sort();
  };
  // What the page needs to start: loaded together rather than one import after another.
  const preload = reach(['import-statement']).filter((f) => f !== entry);
  // What the app can ask for at all: kept for offline. The demo's chunk (and anything only it
  // imports) is fetched when the demo starts, and is never precached.
  const shell = reach(['import-statement', 'dynamic-import']);
  const index = path.join(out, 'index.html');
  const html = readFileSync(index, 'utf8');
  const script = '<script type="module" src="js/main.js"></script>';
  if (!html.includes(script)) { throw new Error(`index.html has no ${script} to load the bundle in its place`); }
  const tags = [...preload.map((f) => `<link rel="modulepreload" href="${f}">`), `<script type="module" src="${entry}"></script>`];
  writeFileSync(index, html.replace(script, tags.join('\n  ')));
  const sw = path.join(out, 'sw.js');
  const source = readFileSync(sw, 'utf8');
  const placeholder = 'const BUNDLE = [];';
  if (!source.includes(placeholder)) { throw new Error(`sw.js has no ${placeholder} to list the bundle in`); }
  writeFileSync(sw, source.replace(placeholder, `const BUNDLE = [${shell.map((f) => `'./${f}'`).join(', ')}];`));
}
// An installed PWA that stays open runs its old code until a new service worker takes
// over, and a browser installs one only when sw.js itself changes. So sw.js carries a
// hash of every other file served, and any change to the app or its relay is an update.
function stampWorker(out) {
  const files = [];
  const walk = (dir) => {
    for (const e of readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, e.name);
      if (e.isDirectory()) { walk(p); } else { files.push(p); }
    }
  };
  walk(out);
  const sw = path.join(out, 'sw.js');
  const hash = createHash('sha256');
  for (const f of files.filter((f) => f !== sw).sort()) {
    hash.update(path.relative(out, f).split(path.sep).join('/')).update('\0').update(readFileSync(f)).update('\0');
  }
  const placeholder = "const VERSION = 'dev';";
  const source = readFileSync(sw, 'utf8');
  if (!source.includes(placeholder)) { throw new Error(`sw.js has no ${placeholder} to stamp`); }
  writeFileSync(sw, source.replace(placeholder, `const VERSION = '${hash.digest('hex').slice(0, 16)}';`));
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const arg = (name) => { const k = process.argv.indexOf(name); return k > 0 ? process.argv[k + 1] : undefined; };
  const out = arg('--out');
  if (!out) { console.error('usage: build-site.mjs --out <dir> [--relay <origin>] [--blob-origin <origin>] [--version <id>] [--built-at <ISO time>] [--feedback-key-id <id> --feedback-public-key <base64url>]'); process.exit(2); }
  buildSite({
    out: path.resolve(out),
    relay: arg('--relay') ?? '',
    blobOrigins: arg('--blob-origin') ? [arg('--blob-origin')] : [],
    version: arg('--version') ?? 'dev',
    builtAt: arg('--built-at') ?? '',
    feedbackKeyId: arg('--feedback-key-id') ?? '',
    feedbackPublicKey: arg('--feedback-public-key') ?? '',
  });
  console.log(`built ${out}${arg('--relay') ? ` for ${arg('--relay')}` : ''}`);
}
